def test_transfer_departs_stock_into_transit(client: TestClient) -> None:
    store_a = _store(client, "Север")
    store_b = _store(client, "Юг")
    item = _item(client, "SKU-101", "Органайзер")
    _inbound(client, store_a["id"], "SKU-101", 10)

    transfer = _transfer(client, store_a["id"], store_b["id"], "SKU-101", 4)

    assert transfer["type"] == "transfer"
    assert transfer["status"] == "in_transit"
    assert transfer["item_id"] == item["id"]
    assert transfer["quantity"] == 4
    assert transfer["src_store_id"] == store_a["id"]
    assert transfer["dest_store_id"] == store_b["id"]

    # The goods left the source; the destination is credited only on receipt.
    assert _stock_of(client, "SKU-101", store_a["id"])["quantity"] == 6
    assert _stock_of(client, "SKU-101", store_b["id"]) is None

    rows = client.get("/stock/in_transit").json()
    assert len(rows) == 1
    assert rows[0]["quantity"] == 4
    assert rows[0]["type"] == "transfer"


