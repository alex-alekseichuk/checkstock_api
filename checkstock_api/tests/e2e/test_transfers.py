def test_full_fbs_lifecycle(client: TestClient, db_query) -> None:
    """inbound -> ship_fbs (reserved) -> approve (shipped) -> receive.

    Also verifies the white-box side: the transfer log carries exactly the
    sequence of state-change events.
    """
    store_a = _store(client, "Север")
    _item(client, "SKU-101")
    _inbound(client, store_a["id"], "SKU-101", 10)
    transfer = _ship(client, "ship_fbs", store_a["id"], "SKU-101", 4)
    _act(client, transfer["id"], "approve")
    received = _act(client, transfer["id"], "receive")

    assert received["status"] == "received"
    row = _stock_of(client, "SKU-101", store_a["id"])
    assert (row["quantity"], row["reserved"]) == (6, 0)

    logs = db_query(
        "SELECT event FROM stock.transfer_logs WHERE transfer_id = $1 ORDER BY id",
        transfer["id"],
    )
    assert [row["event"] for row in logs] == ["reserved", "shipped", "received"]


def test_fbs_cancel_and_new_shipment(client: TestClient) -> None:
    """A canceled FBS reservation frees the stock for a new shipment."""
    store_a = _store(client, "Север")
