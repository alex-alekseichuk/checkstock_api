"""E2E tests for the transfer endpoints.

Covers every flow: ``inbound``, ``transfer``, ``ship_fbo``, ``ship_fbs`` —
their creation, the ``receive`` / ``cancel`` / ``approve`` transitions, and
all domain error cases (404 unknown entity, 400 missing store, 409
insufficient stock / wrong state).
"""

from uuid import UUID

from fastapi.testclient import TestClient


def _store(client: TestClient, title: str) -> dict:
    response = client.post("/stores/", json={"title": title})
    assert response.status_code == 201
    return response.json()


def _item(client: TestClient, sku: str, title: str = "Item") -> dict:
    response = client.post("/items/", json={"sku": sku, "title": title})
    assert response.status_code == 201
    return response.json()


def _post_transfer(client: TestClient, payload: dict) -> "TestClient":
    return client.post("/transfers/", json=payload)


def _inbound(client: TestClient, dest_id: str, sku: str, quantity: int) -> dict:
    response = _post_transfer(
        client, {"type": "inbound", "dest_store_id": dest_id, "sku": sku, "quantity": quantity}
    )
    assert response.status_code == 201
    return response.json()


def _transfer(client: TestClient, source_id: str, dest_id: str, sku: str, quantity: int) -> dict:
    response = _post_transfer(
        client,
        {
            "type": "transfer",
            "source_store_id": source_id,
            "dest_store_id": dest_id,
            "sku": sku,
            "quantity": quantity,
        },
    )
    assert response.status_code == 201
    return response.json()


def _ship(client: TestClient, transfer_type: str, source_id: str, sku: str, quantity: int) -> dict:
    response = _post_transfer(
        client, {"type": transfer_type, "source_store_id": source_id, "sku": sku, "quantity": quantity}
    )
    assert response.status_code == 201
    return response.json()


def _stock_of(client: TestClient, sku: str, store_id: str) -> dict | None:
    rows = client.get("/stock/").json()
    return next((row for row in rows if row["item_sku"] == sku and row["store_id"] == store_id), None)


def _act(client: TestClient, transfer_id: str, action: str) -> dict:
    response = client.post(f"/transfers/{transfer_id}/{action}")
    assert response.status_code == 200
    return response.json()


# --- inbound ------------------------------------------------------------------


def test_inbound_creates_received_transfer_and_adds_stock(client: TestClient) -> None:
    store = _store(client, "Север")
    item = _item(client, "SKU-101", "Органайзер")

    transfer = _inbound(client, store["id"], "SKU-101", 10)

    assert transfer["type"] == "inbound"
    assert transfer["status"] == "received"
    assert transfer["item_id"] == item["id"]
    assert transfer["quantity"] == 10
    assert transfer["src_store_id"] is None
    assert transfer["dest_store_id"] == store["id"]
    assert len(transfer["id"]) == 36  # uuid generated by the DB
    assert transfer["created_at"]
    assert transfer["updated_at"]

    row = _stock_of(client, "SKU-101", store["id"])
    assert row is not None
    assert (row["quantity"], row["reserved"], row["available"]) == (10, 0, 10)


def test_repeated_inbound_accumulates_stock(client: TestClient) -> None:
    store = _store(client, "Север")
    _item(client, "SKU-101")

    _inbound(client, store["id"], "SKU-101", 5)
    _inbound(client, store["id"], "SKU-101", 3)

    row = _stock_of(client, "SKU-101", store["id"])
