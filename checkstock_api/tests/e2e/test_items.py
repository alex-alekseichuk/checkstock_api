"""E2E tests for the items endpoint (``POST /items/``)."""

from fastapi.testclient import TestClient


def _create_item(client: TestClient, sku: str, title: str = "Item") -> dict:
    response = client.post("/items/", json={"sku": sku, "title": title})
    assert response.status_code == 201
    return response.json()


def test_create_item_returns_created_item(client: TestClient) -> None:
    item = _create_item(client, "SKU-101", "Органайзер")

    assert item["sku"] == "SKU-101"
    assert item["title"] == "Органайзер"
    assert len(item["id"]) == 36  # uuid generated by the DB
    assert item["created_at"]  # timestamp generated by the DB


def test_create_item_requires_sku_and_title(client: TestClient) -> None:
    assert client.post("/items/", json={"title": "no sku"}).status_code == 422
    assert client.post("/items/", json={"sku": "SKU-1"}).status_code == 422
    assert client.post("/items/", json={}).status_code == 422


def test_created_item_is_persisted(client: TestClient) -> None:
    """An item survives the request: receiving stock into it shows up in /stock/."""
    store = client.post("/stores/", json={"title": "Север"}).json()
    item = _create_item(client, "SKU-102", "Кейс")

    response = client.post(
        "/transfers/",
        json={"type": "inbound", "dest_store_id": store["id"], "sku": "SKU-102", "quantity": 7},
    )
    assert response.status_code == 201

    rows = client.get("/stock/").json()
    assert any(
        row["item_id"] == item["id"] and row["item_sku"] == "SKU-102" and row["quantity"] == 7
        for row in rows
    )
