"""E2E tests for the stores endpoints (``POST /stores/``, ``DELETE /stores/{id}/``)."""

from uuid import UUID

from fastapi.testclient import TestClient


def _create_store(client: TestClient, title: str = "Store", status: str = "active") -> dict:
    response = client.post("/stores/", json={"title": title, "status": status})
    assert response.status_code == 201
    return response.json()


def test_create_store_defaults_to_active(client: TestClient) -> None:
    response = client.post("/stores/", json={"title": "Север"})
    assert response.status_code == 201

    store = response.json()
    assert store["title"] == "Север"
    assert store["status"] == "active"
    assert len(store["id"]) == 36  # uuid generated by the DB
    assert store["created_at"]


def test_create_store_with_explicit_status(client: TestClient) -> None:
    store = _create_store(client, "Юг", status="closed")
    assert store["status"] == "closed"


def test_create_store_requires_title(client: TestClient) -> None:
    assert client.post("/stores/", json={}).status_code == 422


def test_create_store_rejects_unknown_status(client: TestClient) -> None:
    assert client.post("/stores/", json={"title": "X", "status": "paused"}).status_code == 422


def test_close_empty_store(client: TestClient) -> None:
    store = _create_store(client)

    response = client.delete(f"/stores/{store['id']}/")

    assert response.status_code == 200
    assert response.json()["id"] == store["id"]
    assert response.json()["status"] == "closed"


def test_close_missing_store_returns_404(client: TestClient) -> None:
    response = client.delete(f"/stores/{UUID(int=1)}/")

    assert response.status_code == 404
    assert "not found" in response.json()["detail"]


def test_close_store_with_stock_returns_409(client: TestClient) -> None:
    store = _create_store(client)
    client.post("/items/", json={"sku": "SKU-1", "title": "Item"})
    response = client.post(
        "/transfers/",
        json={"type": "inbound", "dest_store_id": store["id"], "sku": "SKU-1", "quantity": 5},
    )
    assert response.status_code == 201

    response = client.delete(f"/stores/{store['id']}/")

    assert response.status_code == 409
    assert "not empty" in response.json()["detail"]


def test_close_store_with_invalid_uuid_returns_422(client: TestClient) -> None:
    assert client.delete("/stores/not-a-uuid/").status_code == 422
