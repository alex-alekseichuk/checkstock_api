"""Swagger web UI for the checkstock API.

Serves a standalone Swagger UI page at ``/docs`` (replacing FastAPI's
built-in one) and redirects ``/`` to it. The OpenAPI schema itself is
still generated by FastAPI and served at ``/openapi.json``.
"""

from __future__ import annotations

from fastapi import APIRouter
from fastapi.responses import HTMLResponse, RedirectResponse

# Swagger UI standalone assets; the browser loads them from the CDN at page load.
SWAGGER_UI_CDN = "https://unpkg.com/swagger-ui-dist@5"

DOCS_HTML = """\
<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1">
    <title>{title} — Swagger UI</title>
    <link rel="stylesheet" href="{cdn}/swagger-ui-bundle.css">
</head>
<body>
    <div id="swagger-ui"></div>
    <script src="{cdn}/swagger-ui-bundle.js"></script>
    <script>
        const ui = new SwaggerUIBundle({{
            url: "/openapi.json",
            dom_id: "#swagger-ui",
            deepLinking: true,
            presets: [
                SwaggerUIBundle.presets.apis,
                SwaggerUIBundle.plugins.DownloadUrl,
            ],
        }});
    </script>
</body>
</html>
"""


def create_docs_router(title: str) -> APIRouter:
    """Build the router that serves the Swagger UI page and the ``/`` redirect."""
    router = APIRouter()

    @router.get("/", response_class=RedirectResponse)
    async def index() -> RedirectResponse:
        """Landing page: send visitors to the Swagger UI."""
        return RedirectResponse(url="/docs", status_code=307)

    @router.get("/docs", response_class=HTMLResponse)
    async def docs() -> HTMLResponse:
        """Interactive Swagger UI for the OpenAPI schema."""
        return HTMLResponse(DOCS_HTML.format(title=title, cdn=SWAGGER_UI_CDN))

    return router
